namespace Zev.Api.Tests;

// PUT /api/system/memberships/{id}: "Uredi" on a manual role, same rules as a new assignment.
public sealed class MembershipUpdateApiTests
{
    [Fact]
    public async Task SystemAdministratorChangesUserZevAndRoleOfAnAssignment()
    {
        using var factory = new TestFactory();
        var seed = await SeedAsync(factory);
        using var admin = Client(factory, seed.SystemAdminId);
        var path = $"/api/system/memberships/{seed.MembershipId}";
        var current = await ReadAsync(await admin.GetAsync($"/api/system/memberships?pageSize=100"), HttpStatusCode.OK);
        var row = current.GetProperty("items").EnumerateArray().Single(item => item.GetProperty("id").GetGuid() == seed.MembershipId);
        Assert.Equal(seed.ZevAId, row.GetProperty("zevId").GetGuid());
        var rowVersion = row.GetProperty("rowVersion").GetString();
        object Change(string role, Guid? zevId, Guid? userId = null, string? version = null) => new
        {
            userId = userId ?? seed.ManagerId, organizationId = seed.OrganizationId, zevId, role, rowVersion = version ?? rowVersion
        };

        var saved = await ReadAsync(await admin.PutAsJsonAsync(path, Change("Accountant", seed.ZevBId, seed.OtherUserId)), HttpStatusCode.OK);
        Assert.Equal("Accountant", saved.GetProperty("role").GetString());
        Assert.Equal(seed.ZevBId, saved.GetProperty("zevId").GetGuid());
        Assert.Equal("other@example.invalid", saved.GetProperty("userEmail").GetString());
        Assert.Equal("ZEV B", saved.GetProperty("zevName").GetString());
        // A stale row version is answered with 409 on SQL Server (row versions are not generated by the in-memory provider).

        var next = saved.GetProperty("rowVersion").GetString();
        Assert.Equal(HttpStatusCode.BadRequest, (await admin.PutAsJsonAsync(path, Change("Owner", seed.ZevAId, version: next))).StatusCode);
        Assert.Equal(HttpStatusCode.BadRequest, (await admin.PutAsJsonAsync(path, Change("OrganizationAdministrator", seed.ZevAId, version: next))).StatusCode);
        Assert.Equal(HttpStatusCode.BadRequest, (await admin.PutAsJsonAsync(path, Change("Manager", null, version: next))).StatusCode);
        Assert.Equal(HttpStatusCode.NotFound, (await admin.PutAsJsonAsync(path, Change("Manager", Guid.NewGuid(), version: next))).StatusCode);
        // The manager already holds Manager in ZEV B through another row.
        Assert.Equal(HttpStatusCode.Conflict, (await admin.PutAsJsonAsync(path, Change("Manager", seed.ZevBId, seed.ManagerId, next))).StatusCode);
        Assert.Equal(HttpStatusCode.NotFound, (await admin.PutAsJsonAsync($"/api/system/memberships/{Guid.NewGuid()}",
            Change("Manager", seed.ZevAId, version: next))).StatusCode);

        using var manager = Client(factory, seed.ManagerId);
        Assert.Equal(HttpStatusCode.Forbidden, (await manager.PutAsJsonAsync(path, Change("Manager", seed.ZevBId, version: next))).StatusCode);

        using var scope = factory.Services.CreateScope();
        var database = scope.ServiceProvider.GetRequiredService<ZevDbContext>();
        var membership = await database.Memberships.SingleAsync(item => item.Id == seed.MembershipId);
        Assert.Equal((seed.OtherUserId, seed.ZevBId, MembershipRole.Accountant), (membership.UserId, membership.ZevId, membership.Role));
        Assert.True(await database.AuditLogs.AnyAsync(item => item.EntityType == "Membership" && item.EntityId == seed.MembershipId.ToString()
            && item.Action == "Modified" && item.ActorUserId == seed.SystemAdminId));
    }

    private sealed record Seed(Guid OrganizationId, Guid ZevAId, Guid ZevBId, Guid ManagerId, Guid OtherUserId, Guid SystemAdminId, Guid MembershipId);

    private static async Task<Seed> SeedAsync(TestFactory factory)
    {
        using var scope = factory.Services.CreateScope();
        var database = scope.ServiceProvider.GetRequiredService<ZevDbContext>();
        database.Database.EnsureCreated();
        var organization = new Organization { Code = "MU", Name = "Uloge" };
        var zevA = new ZevEntity { Organization = organization, Code = "A", Name = "ZEV A" };
        var zevB = new ZevEntity { Organization = organization, Code = "B", Name = "ZEV B" };
        AppUser User(string name) => new() { Email = $"{name}@example.invalid", NormalizedEmail = $"{name}@EXAMPLE.INVALID".ToUpperInvariant() };
        var manager = User("manager"); var other = User("other"); var admin = User("sysadmin");
        admin.IsSystemAdministrator = true;
        var edited = new Membership { User = manager, Organization = organization, Zev = zevA, Role = MembershipRole.Manager };
        database.AddRange(organization, zevA, zevB, manager, other, admin, edited,
            new Membership { User = manager, Organization = organization, Zev = zevB, Role = MembershipRole.Manager });
        await database.SaveChangesAsync();
        return new(organization.Id, zevA.Id, zevB.Id, manager.Id, other.Id, admin.Id, edited.Id);
    }

    private static async Task<JsonElement> ReadAsync(HttpResponseMessage response, HttpStatusCode expected)
    {
        var body = await response.Content.ReadAsStringAsync();
        Assert.True(response.StatusCode == expected, $"Expected {expected}, got {response.StatusCode}: {body}");
        return JsonDocument.Parse(body).RootElement.Clone();
    }

    private static HttpClient Client(TestFactory factory, Guid userId)
    {
        var client = factory.CreateClient(new WebApplicationFactoryClientOptions { BaseAddress = new Uri("https://localhost") });
        client.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer",
            factory.Services.GetRequiredService<TokenService>().CreateAccessToken(new AppUser { Id = userId }).AccessToken);
        return client;
    }


    private sealed class TestFactory : WebApplicationFactory<Program>
    {
        private readonly string databaseName = Guid.NewGuid().ToString();

        protected override void ConfigureWebHost(IWebHostBuilder builder)
        {
            builder.UseEnvironment("Testing");
            builder.ConfigureLogging(logging => logging.ClearProviders());
            builder.ConfigureAppConfiguration((_, configuration) => configuration.AddInMemoryCollection(new Dictionary<string, string?>
            {
                ["ConnectionStrings:Default"] = "Server=localhost;Database=TestOnly;Trusted_Connection=True",
                ["Jwt:SigningKey"] = "test-only-signing-key-with-at-least-32-characters",
                ["Jwt:Issuer"] = "test-issuer",
                ["Jwt:Audience"] = "test-audience"
            }));
            builder.ConfigureTestServices(services =>
            {
                services.RemoveAll<DbContextOptions<ZevDbContext>>();
                services.RemoveAll<IDbContextOptionsConfiguration<ZevDbContext>>();
                services.RemoveAll<ZevDbContext>();
                services.AddDbContext<ZevDbContext>(options => options.UseInMemoryDatabase(databaseName)
                    .ConfigureWarnings(warnings => warnings.Ignore(InMemoryEventId.TransactionIgnoredWarning)));
            });
        }
    }
}
